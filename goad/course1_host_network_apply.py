NETWORKING = Path("/etc/vmware/networking")
NETMAP = Path("/etc/vmware/netmap.conf")
BACKUPS = Path("/etc/vmware/kingdoms-course1-backups")
OWNER = Path("/etc/vmware/kingdoms-course1-owner.json")
VMWARE_NETWORKS = Path("/usr/bin/vmware-networks")
SYSTEMD = Path("/etc/systemd/system")


class NorthSetupError(RuntimeError):
    pass


def run_command(*args, timeout=80):
    try:
        result = subprocess.run(args, capture_output=True, text=True, timeout=timeout, check=False)
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise NorthSetupError("Host command unavailable or timed out: " + args[0]) from exc
    if result.returncode:
        raise NorthSetupError(
            "Host command failed: " + " ".join(map(str, args))
            + ": " + (result.stderr.strip() or result.stdout.strip())[:400]
        )


def operator_inventory():
    """sudo must inspect the original desktop user's registered VMX entries."""
    name = os.environ.get("SUDO_USER")
    if not name or name == "root":
        raise NorthSetupError("Use sudo from the Kali desktop user, not a root login")
    home = Path(pwd.getpwnam(name).pw_dir)
    if not home.is_dir() or home.is_symlink():
        raise NorthSetupError("Cannot establish the VMware desktop inventory owner")
    return home / ".vmware/inventory.vmls"


def snapshot_netmap(path):
    """A missing netmap is normal on some VMware hosts; never manufacture one."""
    path = Path(path)
    if path.is_symlink():
        raise NorthSetupError("Unsafe VMware netmap.conf symlink; manual review required")
    if not path.exists():
        return None, None
    meta = _plain_regular(path)
    return path.read_bytes(), meta


def durable_netmap_backup(folder, original):
    fd, path = tempfile.mkstemp(prefix="netmap-before-north-", suffix=".backup", dir=folder)
    with os.fdopen(fd, "wb") as output:
        os.fchmod(output.fileno(), 0o600)
        output.write(original)
        output.flush()
        os.fsync(output.fileno())
    return path


class VMwareNetworkRestart:
    """Preserve the original VMware netmap state, including its absence."""

    def __init__(self, path, original, metadata, executable=VMWARE_NETWORKS):
        self.path, self.original, self.metadata = Path(path), original, metadata
        self.executable = str(executable)
        self.calls = 0
        self.observed = original

    def __call__(self):
        rolling_back = self.calls != 0
        before, _ = snapshot_netmap(self.path)
        if rolling_back and before != self.observed:
            raise NorthSetupError(
                "VMware netmap changed outside this transaction; manual reconciliation"
            )
        # A failed first startup must still classify the following callback
        # as rollback; otherwise the second restart skips restoring netmap.
        self.calls += 1
        run_command(self.executable, "--stop")
        if rolling_back:
            # A VMware stop may itself rewrite netmap; reject ambiguous state.
            stopped, _ = snapshot_netmap(self.path)
            if stopped != self.observed:
                raise NorthSetupError(
                    "VMware stop changed netmap unexpectedly; manual reconciliation"
                )
            if self.original is None:
                # Only remove netmap bytes generated by THIS observed restart.
                if stopped is not None:
                    self.path.unlink()
            else:
                _atomic_bytes(self.path, self.original, self.metadata)
        try:
            run_command(self.executable, "--start")
        finally:
            self.observed, _ = snapshot_netmap(self.path)
        if rolling_back and self.observed != self.original:
            raise NorthSetupError(
                "VMware netmap was not restored to its baseline; manual reconciliation"
            )


def asset_paths():
    return {
        "helper": Path(HELPER),
        "service": SYSTEMD / SERVICE,
        "timer": SYSTEMD / TIMER,
    }


def systemd_activate():
    run_command("systemctl", "daemon-reload")
    run_command("systemctl", "start", SERVICE)
    run_command("systemctl", "enable", "--now", TIMER)


def systemd_disable():
    run_command("systemctl", "disable", "--now", TIMER)


def systemd_reload():
    run_command("systemctl", "daemon-reload")


def require_explicit_root():
    if os.geteuid() != 0:
        raise NorthSetupError("Explicit sudo/root permission is required")


def apply(provider_dir, reviewed_sha256, networking=NETWORKING, netmap=NETMAP,
          backups=BACKUPS, owner=OWNER, library=None, vmware_networks=VMWARE_NETWORKS):
    """One guarded VMware transaction; all callbacks run inside its lock."""
    require_explicit_root()
    if not re.fullmatch(r"[0-9a-f]{64}", reviewed_sha256 or ""):
        raise NorthSetupError("Supply the reviewed 64-digit lowercase baseline SHA-256")
    if not Path(provider_dir).is_absolute():
        raise NorthSetupError("Provider must be an existing absolute instance path")
    if not vmware_networks.is_file() or not os.access(vmware_networks, os.X_OK):
        raise NorthSetupError("VMware network service executable is missing")
    user_library = library if library is not None else operator_inventory()
    layout = load_course1_topology()

    # This is the initial read-only inspection. It is repeated INSIDE the lock.
    inspect_live(networking=networking, library=user_library)
    if Path(owner).exists() or Path(owner).is_symlink():
        raise NorthSetupError("A NORTH vmnet owner already exists")
    paths = asset_paths()
    for path in paths.values():
        if path.exists() or path.is_symlink():
            raise NorthSetupError("Existing NORTH systemd asset requires reconciliation")
    # Reject a stale reviewed plan before creating even the recovery backups.
    if hashlib.sha256(Path(networking).read_bytes()).hexdigest() != reviewed_sha256:
        raise NorthSetupError("VMware networking changed since reviewed baseline")
    original, metadata = snapshot_netmap(netmap)
    _safe_directory(Path(networking).parent)
    if not Path(backups).exists():
        Path(backups).mkdir(mode=0o700)
    _safe_directory(Path(backups))
    if original is not None:
        netmap_backup = durable_netmap_backup(backups, original)
        print("[BACKUP] VMware netmap original:", netmap_backup, flush=True)
    else:
        print("[BASELINE] VMware netmap.conf is absent; no file will be fabricated", flush=True)
    restart = VMwareNetworkRestart(Path(netmap), original, metadata, vmware_networks)
    lease = None

    def locked_preflight():
        inspect_live(networking=networking, library=user_library)
        current, _ = snapshot_netmap(netmap)
        if current != original:
            raise NorthSetupError("VMware netmap changed since initial plan; refusing host writes")
        for path in paths.values():
            if path.exists() or path.is_symlink():
                raise NorthSetupError("NORTH address asset was created by another process")

    def verify_runtime():
        nonlocal lease
        verify_vmnet_config(Path(networking).read_text(encoding="utf-8"), layout)
        def verify_addr():
            inspect_live_hostaddrs(layout)
            inspect_live_hostaddr_assets(layout)
        lease = install_owned_address_assets(
            layout, paths, systemd_activate, systemd_disable,
            systemd_reload, verify_addr, owner_uid=os.geteuid(),
        )

    try:
        installed = execute_testable_network_transaction(
            Path(networking), Path(backups), Path(owner), Path(provider_dir),
            layout, reviewed_sha256, restart, verify_runtime,
            preflight=locked_preflight,
        )
        print("[PASS] NORTH VMware networking and persistent host addresses installed", flush=True)
        return installed
    except Exception:
        if lease is not None:
            # An error after asset verification/creation must not strand the timer.
            lease.rollback()
        raise



def _reconstruct_committed_vmnet(record, baseline, layout):
    """Prove the immutable owner SHA corresponds to original apply bytes."""
    proposed = render_vmnet_config(baseline.decode("utf-8"), layout).encode("utf-8")
    candidates = {proposed}
    for zone in ("north", "management"):
        segment = layout["segments"][zone]
        number = segment["vmnet"][5:]
        address = segment["host_address"]
        optional = f"answer VNET_{number}_HOSTONLY_HOSTADDR {address}\n".encode("ascii")
        candidates |= {data.replace(optional, b"", 1)
                       for data in tuple(candidates) if optional in data}
    committed = next(
        (data for data in candidates
         if hashlib.sha256(data).hexdigest() == record.get("installed_sha256")),
        None,
    )
    if committed is None:
        raise NorthSetupError("NORTH owner hash does not match a valid committed config")
    return committed


def inspect_installed_north(provider_dir, networking=NETWORKING, owner=OWNER,
                            backups=BACKUPS, owner_uid=0, inspect_host=True):
    """Check installed NORTH ownership before native Kingdoms lifecycle.

    This is read-only. The clean-host preflight must NOT run post-install,
    because the vmnets it rejects are now intentionally owned by NORTH.
    """
    provider = Path(provider_dir)
    if not provider.is_absolute() or provider.is_symlink() or not provider.is_dir():
        raise NorthSetupError("NORTH provider directory missing or unsafe")
    identity = str(provider.resolve(strict=True))
    record_path = Path(owner)
    if record_path.is_symlink() or not record_path.is_file():
        raise NorthSetupError("NORTH host network owner record is missing or unsafe")
    metadata = _plain_regular(record_path)
    if metadata.st_uid != owner_uid or stat.S_IMODE(metadata.st_mode) != 0o600:
        raise NorthSetupError("NORTH owner record permissions are unsafe")
    try:
        record = json.loads(record_path.read_text(encoding="utf-8"))
    except (OSError, ValueError, UnicodeError) as exc:
        raise NorthSetupError("NORTH owner record is unreadable") from exc

    layout = load_course1_topology()
    vmnets = {name: zone["vmnet"] for name, zone in layout["segments"].items()}
    if (not isinstance(record, dict) or record.get("profile") != "NORTH"
            or record.get("provider") != identity
            or record.get("network_base") != layout["network_base"]
            or record.get("vmnets") != vmnets):
        raise NorthSetupError("NORTH networking belongs to another instance or profile")
    if not isinstance(record.get("backup"), str):
        raise NorthSetupError("NORTH owner record has no baseline backup")

    config = Path(networking)
    _plain_regular(config)
    installed = config.read_bytes()
    verify_vmnet_config(installed.decode("utf-8"), layout)

    root = Path(backups)
    if root.is_symlink() or not root.is_dir():
        raise NorthSetupError("NORTH transaction backup directory is unsafe")
    saved = Path(record["backup"])
    if (not saved.is_absolute() or saved.is_symlink()
            or saved.parent.is_symlink()
            or not saved.is_file() or saved.parent.parent != root):
        raise NorthSetupError("NORTH owned networking backup is missing or unsafe")
    if hashlib.sha256(saved.read_bytes()).hexdigest() != record.get("baseline_sha256"):
        raise NorthSetupError("NORTH backup does not match its ownership record")
    journals = inspect_vmnet_journals(root)
    if any(item["state"] not in ("COMMITTED", "ROLLED_BACK") for item in journals):
        raise NorthSetupError("Unresolved NORTH transaction requires reconciliation")
    matching = [item for item in journals
                if item["state"] == "COMMITTED"
                and item["backup"] == str(saved)
                and item["provider"] == identity
                and item["baseline_sha256"] == record["baseline_sha256"]]
    if len(matching) != 1:
        raise NorthSetupError("No unique committed NORTH network transaction matches this instance")

    committed = _reconstruct_committed_vmnet(record, saved.read_bytes(), layout)
    if installed != committed:
        # Full Kingdoms already checks runtime vmnet policy rather than
        # treating the mutable VMware configuration file as immutable.
        # NORTH additionally proves *all* observed changes are explicitly
        # permitted VMware/Vagrant runtime normalization, never silent edits.
        peer_lines = verified_wslpe_peer_additions()
        verify_owned_vmnet_runtime(committed, installed, saved.read_bytes(), layout,
                                   peer_additions=peer_lines)

    if inspect_host:
        inspect_live_hostaddrs(layout)
        inspect_live_hostaddr_assets(layout)
    return (
        "NORTH immutable owner, baseline backup and committed journal match the instance",
        "NORTH live vmnets and permitted VMware/Vagrant normalization verified",
    )




def diagnose_installed_north(provider_dir, networking=NETWORKING, owner=OWNER,
                             backups=BACKUPS, owner_uid=0):
    """Read-only byte comparison of VMware's *current* config with owned bytes.

    Reconstruct the exact committed bytes from the owner baseline and the
    optional host-address lines that VMware is allowed to remove at apply time.
    Never silently rebase the owner SHA or weaken the native provider guard.
    """
    provider = Path(provider_dir)
    if not provider.is_absolute() or provider.is_symlink() or not provider.is_dir():
        raise NorthSetupError("NORTH provider directory is missing or unsafe")
    identity = str(provider.resolve(strict=True))
    record_file = Path(owner)
    if record_file.is_symlink() or not record_file.is_file():
        raise NorthSetupError("NORTH owner record is missing or unsafe")
    meta = _plain_regular(record_file)
    if meta.st_uid != owner_uid or stat.S_IMODE(meta.st_mode) != 0o600:
        raise NorthSetupError("NORTH owner record ownership or mode is unsafe")
    record = json.loads(record_file.read_text(encoding="utf-8"))
    if not isinstance(record, dict) or record.get("profile") != "NORTH" or record.get("provider") != identity:
        raise NorthSetupError("NORTH owner record belongs to a different instance")
    backup_root = Path(backups)
    if backup_root.is_symlink() or not backup_root.is_dir():
        raise NorthSetupError("NORTH backup directory is unsafe")
    saved_name = record.get("backup")
    if not isinstance(saved_name, str):
        raise NorthSetupError("NORTH owner record has no backup")
    saved = Path(saved_name)
    if (not saved.is_absolute() or saved.is_symlink() or saved.parent.is_symlink()
            or saved.parent.parent != backup_root):
        raise NorthSetupError("NORTH backup path escaped its owned directory")
    _plain_regular(saved)
    baseline = saved.read_bytes()
    if hashlib.sha256(baseline).hexdigest() != record.get("baseline_sha256"):
        raise NorthSetupError("NORTH backup checksum differs from the owner record")
    layout = load_course1_topology()
    owned = _reconstruct_committed_vmnet(record, baseline, layout)
    path = Path(networking)
    if path.is_symlink():
        raise NorthSetupError("Unsafe VMware networking symlink")
    _plain_regular(path)
    current = path.read_bytes()
    exact = current == owned
    try:
        verify_vmnet_config(current.decode("utf-8"), layout)
        topology = "PASS"
    except (ValueError, UnicodeError) as exc:
        topology = "FAIL: " + str(exc)
    # Limit display to changed lines, not an uncontrolled full file dump.
    diff = list(difflib.unified_diff(
        owned.decode("utf-8").splitlines(),
        current.decode("utf-8", errors="replace").splitlines(),
        fromfile="owned-at-commit", tofile="vmware-now", lineterm="",
    ))
    return {
        "provider": identity,
        "owned_sha256": record["installed_sha256"],
        "observed_sha256": hashlib.sha256(current).hexdigest(),
        "exact_match": exact,
        "vmnet_topology": topology,
        "diff": diff[:100],
        "diff_truncated": len(diff) > 100,
    }



def main():
    # The original --north apply CLI remains unchanged. Verification is a
    # distinct, root-readable, read-only action; never call apply from it.
    if len(sys.argv) > 1 and sys.argv[1] == "diagnose":
        parser = argparse.ArgumentParser(description="Read-only NORTH VMware byte drift diagnosis")
        parser.add_argument("--provider-dir", required=True)
        args = parser.parse_args(sys.argv[2:])
        try:
            require_explicit_root()
            result = diagnose_installed_north(args.provider_dir)
            print("[OWNED SHA256] " + result["owned_sha256"])
            print("[CURRENT SHA256] " + result["observed_sha256"])
            print("[TOPOLOGY] " + result["vmnet_topology"])
            print("[BYTE MATCH] " + ("YES" if result["exact_match"] else "NO"))
            if not result["exact_match"]:
                print("[DIFF] Changes since the verified NORTH network commit:")
                for line in result["diff"]:
                    print(line)
                if result["diff_truncated"]:
                    print("[DIFF] Truncated after 100 lines")
                parser.exit(2, "[BLOCKED] NORTH VMnet contents drifted; no changes made\n")
            print("[PASS] NORTH VMware networking still matches the original commit")
        except (NorthSetupError, ValueError, OSError, RuntimeError) as exc:
            parser.exit(1, "[BLOCKED] NORTH drift diagnosis: " + str(exc) + "\n")
        return
    if len(sys.argv) > 1 and sys.argv[1] == "verify":
        parser = argparse.ArgumentParser(description="Read-only NORTH ownership check")
        parser.add_argument("--provider-dir", required=True)
        args = parser.parse_args(sys.argv[2:])
        try:
            require_explicit_root()
            for proof in inspect_installed_north(args.provider_dir):
                print("[PASS] " + proof)
        except (NorthSetupError, ValueError, OSError, RuntimeError) as exc:
            parser.exit(1, "[BLOCKED] NORTH ownership verification: " + str(exc) + "\n")
        return
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--provider-dir", required=True)
    parser.add_argument("--reviewed-sha256", required=True)
    args = parser.parse_args()
    try:
        apply(args.provider_dir, args.reviewed_sha256)
    except (NorthSetupError, ValueError, OSError, RuntimeError) as exc:
        parser.exit(1, "[BLOCKED] Course 1 host setup: " + str(exc) + "\n")


if __name__ == "__main__":
    main()
